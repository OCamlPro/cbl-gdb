class LNS_REGISTERS
{
public:
    // These are the machine state registers as required by the standard
    ULONGLONG   address;        /*  The program-counter value corresponding to a machine instruction generated by the compiler. */
    ULONGLONG   op_index;       /*  An unsigned integer representing the index of an operation within a VLIW instruction. The
                                        index of the first operation is 0. For non-VLIW architectures, this register will always be 0.
                                        The address and op_index registers, taken together, form an operation pointer that can
                                        reference any individual operation with the instruction stream. */
    ULONGLONG   file_number;    /*  An unsigned integer indicating the identity of the source file corresponding to a machine instruction. */
    ULONGLONG   line;           /*  An unsigned integer indicating a source line number. Lines are numbered beginning at 1. The compiler
                                        may emit the value 0 in cases where an instruction cannot be attributed to any source line. */
    ULONGLONG   column;         /*  An unsigned integer indicating a column number within a source line. Columns are numbered beginning
                                        at 1. The value 0 is reserved to indicate that a statement begins at the “left edge” of the line. */
    bool        is_stmt;        /*  A boolean indicating that the current instruction is a recommended breakpoint location. A recommended
                                        breakpoint location is intended to “represent” a line, a statement and/or a semantically distinct
                                        subpart of a statement. */
    bool        basic_block;    /*  A boolean indicating that the current instruction is the beginning of a basic block. */
    bool        end_sequence;   /*  A boolean indicating that the current address is that of the first byte after the end of a sequence
                                        of target machine instructions. end_sequence terminates a sequence of lines; therefore other
                                        information in the same row is not meaningful.  */
    bool        prologue_end;   /*  A boolean indicating that the current address is one (of possibly many) where execution should be
                                        suspended for an entry breakpoint of a function. */
    bool        epilogue_begin; /*  A boolean indicating that the current address is one (of possibly many) where execution should be
                                        suspended for an exit breakpoint of a function. */
    ULONGLONG   isa;            /*  An unsigned integer whose value encodes the applicable instruction set architecture for the
                                        current instruction. */
    ULONGLONG   discriminator;  /*  An unsigned integer identifying the block to which the current instruction belongs.
                                        Discriminator values are assigned arbitrarily by the DWARF producer and serve to distinguish
                                        among multiple blocks that may all be associated with the same source file, line, and
                                        column. Where only one block exists for a given source position, the discriminator value
                                        should be zero.*/

    bool default_is_stmt;       /* Provided by the line program header */
    bool new_statement; // Used by the show_your_work routines; it means this set of values was added into the matrix

public:
    void SetDefaultIsStmt(bool bdefault_is_stmt)
    {
        default_is_stmt = bdefault_is_stmt;
    }
    void Init();
    LNS_REGISTERS();
    LNS_REGISTERS(bool bdefault_is_stmt);
};
typedef std::vector<LNS_REGISTERS>VLNS_REGISTERS;

class LNS_FILE_NAME
{
public:
    std::string name;
    ULONGLONG include_directory_index;
    ULONGLONG time_modified;
    ULONGLONG file_length;

    LNS_FILE_NAME()
    {
        include_directory_index = 0;
        time_modified = 0;
        file_length = 0;
    }
};
typedef std::vector<LNS_FILE_NAME>VLNS_FILE_NAMES;

class ADDRESS_LINE_PAIR
{
public:
    ULONGLONG   address;
    int         file_number;
    ULONGLONG   line;
};
typedef std::vector<ADDRESS_LINE_PAIR>VADDRESS_LINE_PAIRS;

class LNS_STATE_MACHINE
{
private:
    LNS_REGISTERS current_registers;
    VLNS_REGISTERS line_address_matrix;

    // The following variables are for analyzing a .debug_line section.
    CPCHAR line_program_data;        // This is the pointer used to scan through the .debug_line section
    CPCHAR line_program_data_end;    // Don't scan past this location
    bool bIs64;

    // ***************** The following values come from the Line Number Program Header
    ULONGLONG   unit_length;
    USHORT      section_version;
    ULONGLONG   header_length;
    UBYTE       minimum_instruction_length;
    UBYTE       maximum_operations_per_instruction;
    bool        default_is_stmt;
    BYTE        line_base;
    UBYTE       line_range;
    UBYTE       opcode_base;
    UBYTE       standard_opcode_lengths[256];       // Elements 1 through opcode_base-1 are populated
    std::vector<std::string> include_directories;   // Current directory of the compilation is understood
    // to be entry zero and is not explicitly included.
    VLNS_FILE_NAMES lns_file_names;                 // File names start with the index of 1
    // *****************

    void ReadProgramHeader(CPCHAR pdata);
    void DecodeSpecialOpcode(UBYTE opcode, ULONGLONG &delta_address,LONGLONG &delta_line,ULONGLONG &op_index);
    void ProcessSpecialOpcode(UBYTE opcode);
    void StateMachineDifference(UBYTE opcode, UBYTE extended_opcode, const LNS_REGISTERS &in, const LNS_REGISTERS &out);

public:
    LNS_STATE_MACHINE()
    {
        opcode_base = 9;
        minimum_instruction_length = 1;
        maximum_operations_per_instruction = 1;
        line_base = 1;
        line_range = 1;
    }
    void Run(char *line_data,bool show_your_work);
    UBYTE GetOpcodeBase() const
    {
        return opcode_base;
    }
    const UBYTE *StandardOpcodeLengths() const
    {
        return standard_opcode_lengths;
    }
    USHORT GetSectionVersion() const
    {
        return section_version;
    }
    bool GetDwarf64() const
    {
        return bIs64;
    }

    static LONGLONG ProcessSingleExpression(CPCHAR &p,bool bIsTarget64);
};


class LNS_BUILDER
{
private:
    LNS_REGISTERS current_registers;
    VLNS_REGISTERS line_address_matrix;
    VADDRESS_LINE_PAIRS address_line_pairs;

    // The .debug_line state machine programming starts with a relocatable
    // address.  When we build our own new .debug_line program, the location of
    // that relocatable address changes.  We save it here, so that the calling
    // routine can pick it up and use it to modify .rela_debug_line.
    ULONGLONG relocation_address_offset;

    std::vector<UBYTE>line_program; // This is where we synthesize a .debug_line section

    bool bIs64;

    // The following values come from the Line Number Program Header
    ULONGLONG   unit_length;
    USHORT      section_version;
    ULONGLONG   header_length;
    UBYTE       minimum_instruction_length;
    UBYTE       maximum_operations_per_instruction;
    bool        default_is_stmt;
    BYTE        line_base;
    UBYTE       line_range;
    UBYTE       opcode_base;
    UBYTE       standard_opcode_lengths[256];       // Elements 1 through opcode_base-1 are populated
    std::vector<std::string> include_directories;   // Current directory of the compilation is understood
    // to be entry zero and is not explicitly included.
    VLNS_FILE_NAMES lns_file_names;                 // File names start with the index of 1

public:
    LNS_BUILDER()
    {
    }

    void PushValues(const UBYTE *p,size_t length);
    void PushValues(std::vector<UBYTE>vals);
    template<typename T>void Overwrite(ULONGLONG location, T v);
    template<typename T>void PushValue(T v);
    void PushULEB128(ULONGLONG v);
    void PushLEB128(LONGLONG v);

    void SetParams(     USHORT   section_version
                        ,    UBYTE   min_inst_length
                        ,    UBYTE   max_ops_per_instr
                        ,    BYTE    line_base
                        ,    UBYTE   line_range
                        ,    UBYTE   opcode_base
                        ,    bool    default_is_stmt
                        ,    const UBYTE *standard_opcode_lengths
                  );
    int AddFile(const std::string &filename);

    void AddToAddressLineList(ULONGLONG address, int file_number, ULONGLONG line);
    std::vector<UBYTE> BuildProgram();
    size_t GetLineProgramSize() const
    {
        return line_program.size();
    }

    const char * GetLineProgramData() const
    {
        return (const char *)line_program.data();
    }

    const ULONGLONG GetRelocationAddressOffset() const
    {
        return relocation_address_offset;
    }
};

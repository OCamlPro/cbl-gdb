#include <vector>
#include <fstream>
#include <iostream>
#include <set>
#include <map>
#include "input_scan.h"

/*  These objects are for keeping track of the parsed storage section

    The source data is the .cbl.lst file generated by GncCOBOL; it typically
    looks like this:

    ======================

SIZE  TYPE           LVL  NAME                           PICTURE

PROGRAM                   RTEST

LOCAL-STORAGE SECTION

00003 GROUP          01   GETTSYBURG-ADDRESS
00001 NUMERIC        02   FOUR                           9
00002 NUMERIC        02   SCORE                          99

PROGRAM             JIMBOB

WORKING-STORAGE SECTION

00022 GROUP          01   WS-JIM
00010 ALPHABETIC     02   WS-FIRSTNAME                   A(10)
00001 ALPHABETIC     02   WS-MIDDLE-INITIAL              A(1)
00001 ALPHABETIC     02   FILLER                         A(1)
00010 ALPHABETIC     02   WS-LASTNAME                    A(10)
00004 NUMERIC        01   WS-FLOATTEST                   S9(7)V9(8) COMP-1


    ===========================================

    It's a tree structure, so we'll store it that way.


*/

constexpr int LEVEL_ROOT    = -3;
constexpr int LEVEL_PROGRAM = -2;
constexpr int LEVEL_SECTION = -1;
constexpr int LEVEL_FILE    = 0;    // Special handling for the FILE type
constexpr int LEVEL_01      = 01;   // Just to avoid magic numbers;
constexpr int LEVEL_66      = 66;   // ibid.;
constexpr int LEVEL_77      = 77;   // ibid.;
constexpr char SECTION_INPUT_OUTPUT[]= "INPUT-OUTPUT";

typedef std::pair<std::string,std::string> PSS;
typedef std::map<PSS,std::string>MPSS;
typedef std::map<PSS,int>MPSSI;

class VAR_NODE;
typedef std::vector<VAR_NODE *>VVAR_NODES;

typedef struct {
    std::string base_symbol;
    int         offset;
    VAR_NODE   *pvar_node;
} BOP;
typedef std::vector<BOP>VBOP;

class VAR_NODE
{
private:
    // This is stuff we get from the .cbl.lst file:
    std::string program;            // From the two-element PROGRAM line
    std::string section;            // From the two-element SECTION line

    int         size;               // Size in bytes
    std::string type;               // GROUP, NUMERIC, ALPHABETIC
    int         level;              // COBOL identifier level
    // DATA section is level 00
    // The PROGRAM-ID is level -1
    // The ROOT is level -2
    std::string name;               // COBOL identifier
    std::string picture;            // Reported PICTURE string
    std::string usage;              // Reported USAGE string
    std::string redefines;          // Identifier this one REDEFINES
    int         occurs;             // Non-zero means this is a table

    // Here we keep track of the tree
    VAR_NODE *parent;
    VVAR_NODES children;
    VVAR_NODES renamed_by;          // When somebody cites us as an 66/RENAMES,
    //                              // we save them here so we can update
    //                              // them later

    // This is stuff we build once we've created the tree
    std::string canonical_name;     // The full COBOL A in B in C identifier
    std::string base_symbol;        // The b_ base for this variable
    //                              // from our 01 ancestor
    int         offset;             // The total offset to this identifier
    std::string field_symbol;       // The f_ symbol for this variable
    std::string attr_symbol;        // The a_ symbol for this variable

    // This is stuff we got from the .h files:
    int field_size;
    int attr_type;
    int attr_digits;
    int attr_scale;
    int attr_flags;

public:
    VAR_NODE();

    void AddChild(VAR_NODE *new_node);
    std::string
    GetProgram() const
    {
        return program;
    }
    std::string
    GetSection() const
    {
        return section;
    }
    std::string
    GetCanonicalName() const
    {
        return canonical_name;
    }
    std::string
    GetName() const
    {
        return name;
    }
    std::string
    GetBaseSymbol() const
    {
        return base_symbol;
    }
    std::string
    GetFieldSymbol() const
    {
        return field_symbol;
    }
    std::string
    GetAttributeSymbol() const
    {
        return attr_symbol;
    }
    std::string
    GetType() const
    {
        return type;
    }
    std::string
    GetPicture() const
    {
        return picture;
    }
    std::string
    GetUsage() const
    {
        return usage;
    }
    int
    GetOccurs() const
    {
        return occurs;
    }
    int
    GetSize() const
    {
        return size;
    }
    int
    GetLevel() const
    {
        return level;
    }
    int
    GetOffset() const
    {
        return offset;
    }
    int
    GetFieldSize() const
    {
        return field_size;
    }
    int
    GetAttrType() const
    {
        return attr_type;
    }
    int
    GetAttrDigits() const
    {
        return attr_digits;
        ;
    }
    int
    GetAttrScale() const
    {
        return attr_scale;
    }
    int
    GetAttrFlags() const
    {
        return attr_flags;
    }
    VVAR_NODES
    GetChildren()
    {
        return children;
    }

    friend class VARIABLE_TREE;
};
typedef std::vector<VAR_NODE *>VVAR_NODES;

class VARIABLE_TREE
{
private:
    VAR_NODE *root;
    VBOP vbop;
    VVAR_NODES flat_list;

    int         current_level_in_dump;
    std::string current_program_in_dump;
    std::string current_section_in_dump;

    void ChopDownTheTree(VAR_NODE *);
    void DumpNode(std::ostream &sout, const VAR_NODE *node);
    void FindParentOf(std::vector<VAR_NODE *> &parents,int level);
    void ForceParent(VVAR_NODES &parents,const std::string &program_id);
    void BuildCanonicalName(VAR_NODE *var_node);
    void AssignBaseSymbol(VAR_NODE *node,const MPSS &symmap);
    void AssignBaseSymbol(VAR_NODE *node,
                          const MPSSI &symmap,
                          const DATA_DESCRIPTIONS &data_description
                         );
    void BuildBaseOffsetPointers(VAR_NODE *node,VBOP &vbop);
    void BuildFlatList(VAR_NODE *node,VVAR_NODES &flat);
    void MergeWorkingStorage(const DATA_DESCRIPTIONS &data_description);
    void MergeLocalStorage(const DATA_DESCRIPTIONS &data_description);

public:
    VARIABLE_TREE();
    ~VARIABLE_TREE();
    void ChopDownTheTree();
    void ReadFromFile(std::ifstream &ifs);
    void BuildCanonicalName();
    void Dump(std::ostream &s = std::cout);
    void Merge(const DATA_DESCRIPTIONS &data_description);

    int
    size() const
    {
        return (int)flat_list.size();
    }

    VAR_NODE
    operator[](int i) const
    {
        return *flat_list[i];
    }
};